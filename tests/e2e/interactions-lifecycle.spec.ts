import { expect, test } from "@playwright/test";
import { native, prepare } from "./support/interactions";

test("keeps centroid overlays current through scenes, deletion and project changes", async ({ page, request }, info) => {
  test.skip(info.project.name !== "chromium", "Complete project-tree workflow is desktop; mobile overlay/remount qualification is separate.");
  test.setTimeout(120_000);
  const other = await (await request.post("/api/v1/projects", { data: { name: `Interaction reset ${Date.now()}` } })).json();
  const project = await prepare(page, request, ["tests/fixtures/interactions/ring_a.mol", "tests/fixtures/interactions/ring_b.mol", "tests/fixtures/interactions/positive_ion.mol"], "Centroid lifecycle");
  let analyses = 0;
  page.on("request", outgoing => { if (outgoing.url().endsWith("/interactions")) analyses++; });
  const launcher = page.getByRole("button", { name: "Interactions", exact: true });
  const panel = page.getByRole("dialog", { name: "Interactions", exact: true });
  await launcher.click();
  await panel.getByRole("button", { name: "π–π", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("1 detected", { timeout: 20_000 });
  await expect.poll(async () => (await native(page)).records.length).toBe(1);
  const ring = (await native(page)).records[0];
  expect(ring.participants.map(group => group.length)).toEqual([6, 6]);
  expect(ring.endpoints[0][2]).toBe(0); expect(ring.endpoints[1][2]).toBe(3.5);
  await panel.getByRole("button", { name: "Cation–π", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("3 detected");
  await expect.poll(async () => new Set((await native(page)).objects[0]?.groups).size).toBe(3);
  const attached = (await native(page)).objects[0];
  expect(attached.drawCount).toBeLessThanOrEqual(attached.indexCapacity);
  expect(attached.starts.length).toBe(attached.drawCount / 6 * 12);
  expect(analyses).toBe(1);
  await panel.getByRole("button", { name: "Close interactions" }).click();
  await page.getByRole("button", { name: "Open viewer controls" }).click();
  await page.getByPlaceholder("Scene name").fill("Centroid checkpoint");
  await page.getByRole("button", { name: "Save current scene" }).click();
  await page.getByRole("button", { name: "Centroid checkpoint", exact: true }).click();
  await page.getByRole("button", { name: "Close viewer controls" }).click();
  await expect.poll(async () => (await native(page)).records.length).toBe(3);
  expect(analyses).toBe(1);
  const row = page.locator(`[data-entry-id="${project.entries[1].id}"]`);
  await row.getByRole("button", { name: /^Hide / }).click();
  await expect(page.locator(".viewer-status")).toContainText("2 visible / 2 loaded");
  await expect.poll(async () => (await native(page)).records.length).toBe(1);
  await row.getByRole("button", { name: /^Show / }).click();
  await expect(page.locator(".viewer-status")).toContainText("3 visible / 3 loaded");
  await expect.poll(async () => (await native(page)).records.length).toBe(3);
  expect(analyses).toBe(1);
  await row.getByRole("button", { name: /^Actions for / }).click();
  await page.getByRole("menuitem", { name: "Delete", exact: true }).click();
  await page.getByRole("dialog", { name: "Delete structure" }).getByRole("button", { name: "Delete", exact: true }).click();
  await expect(page.locator(".viewer-status")).toContainText("2 visible / 2 loaded");
  await expect.poll(async () => (await native(page)).records.length).toBe(1);
  expect(analyses).toBe(1);
  expect((await native(page)).records.every(record => record.participants.flat().every(atom => atom.structure_id !== project.entries[1].id))).toBe(true);
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  await page.getByRole("dialog", { name: "Projects" }).getByRole("button", { name: new RegExp(`^${other.name}`) }).click();
  await page.getByRole("button", { name: "Projects", exact: true }).click();
  await page.getByRole("dialog", { name: "Projects" }).getByRole("button", { name: new RegExp(`^${project.name}`) }).click();
  await expect(page.locator(".viewer-status")).toContainText("2 visible / 2 loaded");
  await launcher.click(); await expect(panel.getByRole("status")).toHaveText("Off");
  await expect(panel.getByRole("button", { name: "π–π", exact: true })).toHaveAttribute("aria-pressed", "false");
  await panel.getByRole("button", { name: "Cation–π", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("1 detected", { timeout: 20_000 });
  await page.reload();
  await expect(page.locator(".viewer-status")).toContainText("2 visible / 2 loaded");
  await launcher.click(); await expect(panel.getByRole("status")).toHaveText("Off");
});
